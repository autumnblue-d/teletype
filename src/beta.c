// Port of stmlib::Interpolate (dsp/dsp.h): fractional table lookup with linear
// interpolation. index in [0,1] maps across the table's `size` span.
static float tt_interpolate(const float *table, float index, float size) {
    index *= size;
    int index_integral = (int)index;
    float index_fractional = index - (float)index_integral;
    float a = table[index_integral];
    float b = table[index_integral + 1];
    return a + (b - a) * index_fractional;
}

float beta_fast(float uniform) {
    if (uniform < 0.0f) { uniform = 0.0f; }
    // Clamp just below 1.0 so index_integral stays < 128 and the lookup never
    // crosses into the second (tail) curve of the table.
    else if (uniform > 0.99996948f) { uniform = 0.99996948f; }
    return tt_interpolate(dist_icdf_4_3, uniform, BETA_ICDF_TABLE_SIZE);
}
